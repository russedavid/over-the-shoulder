"""Native presentation replay of two actual new-system responses; no inference.

This isolates holding/browsing from model behavior. It does not measure fresh
screen-to-answer latency or replace the recorded native pipeline run.
"""

import argparse
import json
import os
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch

import AppKit as A

from evals.continuity import available_code_type
from otsc.app import Controller
from otsc.models import Assistance, Observation
from otsc.native_smoke import publish
from otsc.privacy import private_write
from otsc.settings import Settings
from otsc.telemetry import digest, release_manifest


def replay(source, output):
    output.mkdir(mode=0o700, parents=True, exist_ok=False)
    rows = [json.loads(line) for line in (source / 'timeline.jsonl').read_text().splitlines()]
    selected = []
    for stage in ('initial', 'changed_held'):
        matches = [e for e in rows if e['event'] == 'terminal' and e['stage'] == stage
                   and e.get('published') and e.get('lane') == 'deep'
                   and any(a['kind'] == 'code' for a in e['response']['artifacts'])]
        if not matches:
            raise ValueError('The recorded run did not supply code for ' + stage)
        selected.append(matches[-1])
    os.environ['OTSC_DATA_DIR'] = str(output / 'private-app-state')
    app = A.NSApplication.sharedApplication()
    app.setActivationPolicy_(A.NSApplicationActivationPolicyRegular)
    result = {'source_run': str(source), 'source_journal_hash': digest((source / 'timeline.jsonl').read_text()),
              'source_requests': [e['request_id'] for e in selected], 'release': release_manifest(),
              'live_inference': False, 'hardware_capture': False,
              'scope': 'Native hold/history replay using unchanged responses generated by the current pipeline.',
              'checks': {}}
    with (patch('otsc.app.load_settings', return_value=Settings(configured=True)),
          patch('otsc.app.provider_for', side_effect=AssertionError('Replay must not call providers')),
          patch('otsc.app.AudioCapture.start', side_effect=AssertionError('Replay must not capture audio')),
          patch('pyautogui.screenshot', side_effect=AssertionError('Replay must not capture screen'))):
        c = Controller.alloc().initWithOptions_(SimpleNamespace(demo=False, design_demo=False, smoke_test=None,
                                                               disable_midi=True, trace_source='recorded-presentation-replay'))
        c.timer.invalidate()
        try:
            for index, row in enumerate(selected):
                at = row['snapshot']['recent_window']['end']
                c.context.clock = lambda at=at: at
                # prompt_context stores literal OCR once in text, outside reading.
                observations = [{**o, 'reading': {**o['reading'], 'visible_text': o['text']}}
                                if o.get('reading') else o for o in row['snapshot']['observations']]
                c.context.observations = [Observation.model_validate(o) for o in observations]
                answer = Assistance.model_validate(row['response'])
                answer._task_plan = row['plan']
                answer.validate_sources(c.context.observations, {})
                publish(c, answer)
                if index == 0:
                    key = available_code_type(c.browser)
                    c.browser.select_type(key)
                    c.show_selected_output()
                    original_id, original_text = c.browser.visible.id, c.copy_text()
                    c.save_view_image(output / '01-selected-held.png')
                else:
                    result['checks']['held_identity_preserved'] = c.browser.visible.id == original_id
                    result['checks']['held_text_preserved'] = c.copy_text() == original_text
                    result['checks']['one_new_code_version'] = c.browser.newer_count == 1
                    result['checks']['badge_shows_one'] = c.type_buttons[key].newer_count == 1
                    expected = next(a.content for a in answer.artifacts if a.kind == 'code')
                    memory = json.loads(c.context.previous_answer)
                    result['checks']['latest_memory_updated_while_held'] = any(
                        a['kind'] == 'code' and a['content'] == expected for a in memory['artifacts'])
                    c.save_view_image(output / '02-new-code-available-while-held.png')
                    c.latestOutput_(None)
                    result['checks']['latest_resumes_type'] = not c.browser.frozen and c.browser.newer_count == 0
                    result['checks']['latest_text_is_new_code'] = c.copy_text() == expected
                    c.save_view_image(output / '03-latest.png')
                    c.olderOutput_(None)
                    result['checks']['older_stays_in_type'] = c.browser.active_key == key and c.copy_text() == original_text
                    c.newerOutput_(None)
                    result['checks']['newer_stays_held_in_type'] = c.browser.active_key == key and c.copy_text() == expected and c.browser.frozen
            result['passed'] = all(result['checks'].values())
            private_write(output / 'result.json', json.dumps(result, indent=2))
        finally:
            c.shutdown()
            c.window.orderOut_(None)
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--run', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(replay(args.run.resolve(), args.output.resolve()), indent=2))
